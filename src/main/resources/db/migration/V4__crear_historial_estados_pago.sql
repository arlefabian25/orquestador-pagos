-- Bitácora append-only de transiciones.
CREATE TABLE historial_estados_pago (
    id                   bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intento_pago_id      uuid          NOT NULL REFERENCES intentos_pago (id),
    estado_origen        varchar(20),
    estado_destino       varchar(20)   NOT NULL,
    origen               varchar(20)   NOT NULL
        CHECK (origen IN ('API', 'WEBHOOK', 'RECONCILIATION', 'OPERACION')),
    motivo               varchar(200),
    evento_proveedor_id  uuid          REFERENCES eventos_proveedor (id),
    id_correlacion       varchar(64),
    ocurrido_en          timestamptz   NOT NULL
);
